#!/usr/bin/env python3
"""Generate shim/devcfg.h from the device table (tools/devices.py).

The shim is freestanding C with no build system, so the per-SoC constants
come from here instead of a #ifdef forest:

    python3 tools/gen_devcfg.py chiron > shim/devcfg.h

shim/build.sh does this automatically when given --device NAME.  Without a
devcfg.h the shim still builds for sweet: every macro has a fallback in
console.h / mmu.h / shim.c.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import devices


def emit(dev):
    fb = dev["fb"]
    gic = dev["gic"]
    cores = devices.cpu_list(dev)
    out = []
    w = out.append
    w("/*")
    w(" * Generated by tools/gen_devcfg.py -- do not edit.")
    w(" *")
    w(f" * Device: {dev['name']} ({dev['product']}, {dev['soc_name']})")
    w(" * Facts: see tools/devices.py (live FDT references in the header there).")
    w(" */")
    w("#pragma once")
    w("")
    w(f'#define DCFG_DEVICE                 "{dev["name"]}"')
    w(f'#define DCFG_PRODUCT                "{dev["product"]}"')
    w(f'#define DCFG_SOC                    "{dev["soc"]}"')
    w(f'#define DCFG_PLATFORM_MATCH         "{dev["platform_match"]}"')
    w("")
    w("/* display: the surface the bootloader left the panel running on */")
    w(f"#define DCFG_FB_BASE                0x{fb['base']:08x}UL")
    w(f"#define DCFG_FB_SIZE                0x{fb['size']:08x}UL")
    w(f"#define DCFG_FB_W                   {fb['width']}")
    w(f"#define DCFG_FB_H                   {fb['height']}")
    w(f"#define DCFG_FB_STRIDE              {fb['stride']}")
    w("")
    w("/* GICv3 */")
    w(f"#define DCFG_GICD_BASE              0x{gic['dist']:08x}UL")
    w(f"#define DCFG_GICD_SIZE              0x{gic['dist_size']:08x}UL")
    w(f"#define DCFG_GICR_BASE              0x{gic['redist']:08x}UL")
    w(f"#define DCFG_GICR_SIZE              0x{gic['redist_size']:08x}UL")
    w(f"#define DCFG_GICR_STRIDE            0x{gic['redist_stride']:08x}UL")
    w(f"#define DCFG_VTIMER_INTID           {dev['vtimer_intid']}")
    w(f"#define DCFG_PTIMER_INTID           {dev['ptimer_intid']}")
    w(f"#define DCFG_TIMEBASE               {dev['timebase']}")
    w("")
    w("/* storage: the UFS host the bootloader leaves running */")
    w(f"#define DCFG_UFS_BASE               0x{dev['ufs'][0]:08x}UL")
    w(f"#define DCFG_UFS_SIZE               0x{dev['ufs'][1]:04x}UL")
    w("")
    w("/* reset path (probe mode) */")
    w(f"#define DCFG_PSHOLD                 0x{dev['pshold']:08x}UL")
    w(f"#define DCFG_IMEM_RESTART           0x{dev['imem_restart']:08x}UL")
    w("")
    w(f"#define DCFG_NR_CPUS                {len(cores)}")
    w("/* MPIDR (Aff1:Aff0) of each core, in device-tree order */")
    w("#define DCFG_MPIDRS                 { " +
      ", ".join(f"0x{m:03x}" for m, _c, _k, _b in cores) + " }")
    w("")
    w("/* iPhone identity (the userland comes from this model's IPSW) */")
    w(f'#define DCFG_IDENTITY_TARGET        "{dev["identity"][0]}"')
    w(f'#define DCFG_IDENTITY_MODEL         "{dev["identity"][1]}"')
    w("")
    return "\n".join(out)


if __name__ == "__main__":
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    print(emit(devices.get(sys.argv[1])))
